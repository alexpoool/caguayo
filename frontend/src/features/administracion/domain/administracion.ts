/** Credenciales de acceso visibles solo para administración. */
export interface CredencialUsuario {
  id_usuario: number;
  ci: string;
  nombre: string;
  primer_apellido: string;
  segundo_apellido: string | null;
  alias: string;
  contrasenia: string;
  contrasenia_plana: string | null;
  cargo: string | null;
  id_grupo: number | null;
  id_dependencia: number | null;
  grupo_nombre: string | null;
  dependencia_nombre: string | null;
}

/** Puerto de persistencia de Administración. Adaptador heredado transitorio. */
export interface AdministracionRepositorio {
  getFuncionalidades: () => Promise<Funcionalidad[]>;
  getGrupos: () => Promise<Grupo[]>;
  createGrupo: (data: GrupoCreate) => Promise<Grupo>;
  updateGrupo: (id: number, data: GrupoUpdate) => Promise<Grupo>;
  deleteGrupo: (id: number) => Promise<void>;
  getUsuarios: () => Promise<Usuario[]>;
  createUsuario: (data: UsuarioCreate) => Promise<Usuario>;
  updateUsuario: (id: number, data: UsuarioUpdate) => Promise<Usuario>;
  deleteUsuario: (id: number) => Promise<void>;
  getDependencias: (todas?: boolean) => Promise<Dependencia[]>;
  getDependencia: (id: number) => Promise<Dependencia>;
  createDependencia: (data: DependenciaConCuentasCreate) => Promise<Dependencia>;
  updateDependencia: (id: number, data: DependenciaUpdate) => Promise<Dependencia>;
  deleteDependencia: (id: number) => Promise<{ database_dropped: boolean; database_name: string | null; dependencia_nombre: string; }>;
  getTiposDependencia: () => Promise<TipoDependencia[]>;
  createTipoDependencia: (data: TipoDependenciaCreate) => Promise<TipoDependencia>;
  updateTipoDependencia: (id: number, data: TipoDependenciaUpdate) => Promise<TipoDependencia>;
  deleteTipoDependencia: (id: number) => Promise<void>;
  getProvincias: () => Promise<Provincia[]>;
  getMunicipios: (provinciaId?: number) => Promise<Municipio[]>;
  getCuentasDependencia: (search?: string) => Promise<CuentaDependencia[]>;
  createCuentaDependencia: (data: CuentaDependenciaCreate) => Promise<CuentaDependencia>;
  updateCuentaDependencia: (id: number, data: CuentaDependenciaUpdate) => Promise<CuentaDependencia>;
  deleteCuentaDependencia: (id: number) => Promise<void>;
  getTiposContrato: () => Promise<TipoContrato[]>;
  createTipoContrato: (data: TipoContratoCreate) => Promise<TipoContrato>;
  updateTipoContrato: (id: number, data: TipoContratoUpdate) => Promise<TipoContrato>;
  deleteTipoContrato: (id: number) => Promise<void>;
  getEstadosContrato: () => Promise<EstadoContrato[]>;
  createEstadoContrato: (data: EstadoContratoCreate) => Promise<EstadoContrato>;
  updateEstadoContrato: (id: number, data: EstadoContratoUpdate) => Promise<EstadoContrato>;
  deleteEstadoContrato: (id: number) => Promise<void>;
  getTiposProveedor: () => Promise<TipoProveedor[]>;
  createTipoProveedor: (data: TipoProveedorCreate) => Promise<TipoProveedor>;
  updateTipoProveedor: (id: number, data: TipoProveedorUpdate) => Promise<TipoProveedor>;
  deleteTipoProveedor: (id: number) => Promise<void>;
  getTiposConvenio: () => Promise<TipoConvenio[]>;
  createTipoConvenio: (data: TipoConvenioCreate) => Promise<TipoConvenio>;
  updateTipoConvenio: (id: number, data: TipoConvenioUpdate) => Promise<TipoConvenio>;
  deleteTipoConvenio: (id: number) => Promise<void>;
  getEspecialidades: (soloActivas?: boolean) => Promise<Especialidad[]>;
  createEspecialidad: (data: EspecialidadCreate) => Promise<Especialidad>;
  updateEspecialidad: (id: number, data: EspecialidadUpdate) => Promise<Especialidad>;
  desactivarEspecialidad: (id: number) => Promise<Especialidad>;
  reactivarEspecialidad: (id: number) => Promise<Especialidad>;
  listar: (baseDatos: string) => Promise<BackupListado>;
  crear: (baseDatos: string) => Promise<BackupJobIniciado>;
  restaurar: (baseDatos: string, archivo: string) => Promise<BackupJobIniciado>;
  getJob: (jobId: string) => Promise<BackupJob>;
  eliminar: (archivo: string) => Promise<void>;
  getMonedas: (skip?: number, limit?: number, onTotal?: (t: number | null) => void) => Promise<Moneda[]>;
  createMoneda: (data: MonedaCreate) => Promise<Moneda>;
  updateMoneda: (id: number, data: MonedaUpdate) => Promise<Moneda>;
  deleteMoneda: (id: number) => Promise<void>;
  getCategorias: (skip?: number, limit?: number) => Promise<Categorias[]>;
  createCategoria: (data: CategoriasCreate) => Promise<Categorias>;
  updateCategoria: (id: number, data: CategoriasUpdate) => Promise<Categorias>;
  deleteCategoria: (id: number) => Promise<void>;
  getSubcategorias: (skip?: number, limit?: number) => Promise<Subcategorias[]>;
  createSubcategoria: (data: SubcategoriasCreate) => Promise<Subcategorias>;
  updateSubcategoria: (id: number, data: SubcategoriasUpdate) => Promise<Subcategorias>;
  deleteSubcategoria: (id: number) => Promise<void>;
  getTiposEntidad: () => Promise<TipoEntidad[]>;
  createTipoEntidad: (data: { nombre: string; descripcion?: string; }) => Promise<TipoEntidad>;
  updateTipoEntidad: (id: number, data: { nombre?: string; descripcion?: string; }) => Promise<TipoEntidad>;
  deleteTipoEntidad: (id: number) => Promise<void>;
  listarActividades: () => Promise<ActividadEconomica[]>;
  crearActividad: (data: ActividadEconomicaInput) => Promise<ActividadEconomica>;
  actualizarActividad: (id: number, data: ActividadEconomicaInput) => Promise<ActividadEconomica>;
  eliminarActividad: (id: number) => Promise<void>;
  listarTributos: () => Promise<Tributo[]>;
  crearTributo: (data: TributoInput) => Promise<Tributo>;
  actualizarTributo: (id: number, data: TributoInput) => Promise<Tributo>;
  eliminarTributo: (id: number) => Promise<void>;
  listarCredenciales: () => Promise<CredencialUsuario[]>;
}
